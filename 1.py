def detect_hardware_capabilities():
    if shutil.which("nvidia-smi"):
        try:
            proc = subprocess.run(
                ["nvidia-smi", "--query-gpu=name", "--format=csv,noheader"],
                capture_output=True, text=True, timeout=4, errors="ignore"
            )
            if proc.returncode == 0 and proc.stdout.strip():
                gpus = [line.strip() for line in proc.stdout.strip().split("\n") if line.strip()]
                HARDWARE_INFO["gpu_count"] = len(gpus)
                HARDWARE_INFO["gpu_indices"] = list(range(len(gpus)))
                HARDWARE_INFO["gpu_name"] = f"{len(gpus)}x {gpus[0]}" if len(gpus) > 1 else gpus[0]
        except Exception:
            pass

    try:
        import ctranslate2
        cuda_cnt = ctranslate2.get_cuda_device_count()
        if cuda_cnt > 0:
            HARDWARE_INFO["cuda_available"] = True
    except Exception:
        pass

    for enc in ["h264_nvenc", "h264_qsv", "h264_amf"]:
        try:
            test_cmd = [
                "ffmpeg", "-hide_banner", "-loglevel", "error",
                "-f", "lavfi", "-i", "color=c=black:s=128x128:d=0.1",
                "-c:v", enc, "-f", "null", "-"
            ]
            res = subprocess.run(test_cmd, capture_output=True, timeout=4)
            if res.returncode == 0:
                HARDWARE_INFO["video_encoders"].append(enc)
                if not HARDWARE_INFO["best_gpu_encoder"]:
                    HARDWARE_INFO["best_gpu_encoder"] = enc
        except Exception:
            continue

detect_hardware_capabilities()

