        sig = hmac.new(SERVER_HMAC_SECRET.encode("utf-8"), token_payload.encode("utf-8"), hashlib.sha256).hexdigest()[:16]
        token = f"{token_payload}|{sig}"
        return jsonify({"status": "ok", "token": token})
