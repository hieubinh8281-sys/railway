def do_transcribe_core(video_path, model_size="small", device_req="auto", source_lang="auto", progress_cb=None):
    if progress_cb is None:
        progress_cb = update_progress

    from faster_whisper import WhisperModel
    progress_cb(12, f"Đang khởi tạo Whisper ({model_size}) trên máy trạm...")

    cpu_threads = HARDWARE_INFO["cpu_threads"]
    device_mode = "cpu"
    compute_mode = "int8"
    if device_req == "cuda" or (device_req == "auto" and HARDWARE_INFO.get("cuda_available")):
        try:
            device_mode = "cuda"
            compute_mode = "float16"
            model = WhisperModel(model_size, device=device_mode, compute_type=compute_mode)
        except Exception as e_cuda:
            print(f"[!] Không thể chạy Whisper trên CUDA ({e_cuda}), tự động fallback CPU...")
            device_mode = "cpu"
            compute_mode = "int8"
            model = WhisperModel(model_size, device=device_mode, compute_type=compute_mode, cpu_threads=cpu_threads)
    else:
        model = WhisperModel(model_size, device="cpu", compute_type="int8", cpu_threads=cpu_threads)

    _, _, total_dur = get_video_info(video_path)
    progress_cb(20, f"Bắt đầu tách giọng nói bằng Whisper ({device_mode.upper()})...")

    transcribe_args = {"beam_size": 5}
    if source_lang and source_lang != "auto":
        transcribe_args["language"] = source_lang

    raw_segments, info = model.transcribe(video_path, **transcribe_args)
    detected_lang = getattr(info, "language", None)

    segments = []
    for idx, seg in enumerate(raw_segments, start=1):
        segments.append({
            "id": idx,
            "start": round(seg.start, 2),
            "end": round(seg.end, 2),
            "text": seg.text.strip(),
            "trans": ""
        })
        pct = 25 + (int((seg.end / total_dur) * 72) if total_dur > 0 else min(70, idx))
        progress_cb(min(98, pct), f"Đã tách câu #{idx}: {seg.text[:28]}...")

    progress_cb(100, f"Hoàn tất tách {len(segments)} câu phụ đề!")
    return segments, detected_lang, device_mode

