def do_render_core(segments, settings, video_path=None, output_path=None, work_dir=None, progress_cb=None):
    if progress_cb is None:
        progress_cb = update_progress

    work_dir = work_dir or TEMP_DIR
    os.makedirs(work_dir, exist_ok=True)
    video_path = video_path or os.path.join(work_dir, "input_video.mp4")
    if not os.path.exists(video_path):
        video_path = os.path.join(TEMP_DIR, "input_video.mp4")
    if not os.path.exists(video_path):
        raise FileNotFoundError("Không tìm thấy video đầu vào để render!")

    output_path = output_path or os.path.join(work_dir, "output_vietsub.mp4")

    target_lang = settings.get("targetLang", "vi")
    google_lang_code = settings.get("googleLangCode", target_lang)
    blur_rect = settings.get("blurRect", {"x": 0, "y": 0, "w": 0, "h": 0})
    blur_opacity = float(settings.get("blurOpacity", 40)) / 100.0
    blur_sigma = int(settings.get("blurSigma", 16))
    blur_color = str(settings.get("blurColor", "#000000")).lstrip("#")

    font_name = settings.get("fontName", "Arial")
    font_size = int(settings.get("fontSize", 22))
    text_color = settings.get("textColor", "#E1FF00")
    outline_color = settings.get("outlineColor", "#000000")
    outline_width = int(settings.get("outlineWidth", 2))
    margin_v = int(settings.get("marginV", 28))

    enable_tts = settings.get("enableTts", True)
    tts_voice = settings.get("ttsVoice", "piper:vi_VN-vais1000-medium")
    tts_threads = int(settings.get("ttsThreads", 16))
    reuse_audio_cache = settings.get("reuseAudioCache", True)
    orig_volume = float(settings.get("origVolume", 0.15))
    render_mode = settings.get("renderMode", "hybrid_gpu")

    vid_w, vid_h, total_dur = get_video_info(video_path)

    # Tự động quét SmartBlur nếu chưa vẽ
    if int(blur_rect.get("w", 0)) < 10 and int(blur_rect.get("h", 0)) < 10 and render_mode != "copy":
        try:
            sb_res = auto_detect_smartblur_fullrow(
                video_path,
                scan_minutes=ADDON_SETTINGS.get("smartblur_scan_minutes", 4),
                pad_y=ADDON_SETTINGS.get("smartblur_pad_y", 14),
                progress_cb=progress_cb
            )
            blur_rect = {"x": sb_res["x"], "y": sb_res["y"], "w": sb_res["w"], "h": sb_res["h"]}
        except Exception as e_sb:
            print(f"[!] SmartBlur auto detect notice: {e_sb}")

    srt_path = os.path.join(work_dir, "sub_vi.srt")
    with open(srt_path, "w", encoding="utf-8") as f:
        for idx, seg in enumerate(segments, start=1):
            f.write(f"{idx}\n{format_srt_time(seg['start'])} --> {format_srt_time(seg['end'])}\n{(seg.get('trans') or seg.get('text') or '').strip()}\n\n")

    generate_vtt_file(os.path.join(work_dir, "sub_vi.vtt"), segments)
    ass_path = os.path.join(work_dir, "sub_vi.ass")
    generate_ass_file(ass_path, segments, vid_w, vid_h, font_name, font_size, text_color, outline_color, outline_width, margin_v, target_lang)

    inject_dvd_bouncing_text_into_ass(ass_path, vid_w, vid_h, total_dur, ADDON_SETTINGS)

    final_audio_path = os.path.join(work_dir, "mixed_audio.aac")
    if enable_tts and segments:
        cache_dir = os.path.join(TEMP_DIR, "tts_cache")
        os.makedirs(cache_dir, exist_ok=True)
        total = len(segments)
        done_cnt = 0

        def make_one_audio(seg):
            nonlocal done_cnt
            txt = (seg.get("trans") or seg.get("text") or "").strip()
            if not txt:
                return None
            ckey = get_tts_cache_key(tts_voice, txt)
            cfile = os.path.join(cache_dir, f"{ckey}.mp3")

            if not (reuse_audio_cache and os.path.exists(cfile) and os.path.getsize(cfile) > 100):
                ok = False
                if tts_voice.startswith("piper:"):
                    ok = synthesize_with_piper(txt, tts_voice, cfile)
                elif not tts_voice.startswith("google:"):
                    try:
                        asyncio.run(edge_tts.Communicate(txt, tts_voice).save(cfile))
                        ok = os.path.exists(cfile) and os.path.getsize(cfile) > 100
                    except Exception:
                        ok = False
                if not ok:
                    g_tl = tts_voice.split(":", 1)[1] if tts_voice.startswith("google:") else google_lang_code
                    r = requests.get("https://translate.googleapis.com/translate_tts", params={"ie": "UTF-8", "q": txt[:200], "tl": g_tl, "client": "tw-ob"}, timeout=12)
                    if r.status_code == 200:
                        with open(cfile, "wb") as f:
                            f.write(r.content)

            done_cnt += 1
            progress_cb(15 + int((done_cnt / max(1, total)) * 45), f"Đang tạo giọng đọc ({done_cnt}/{total} câu)...")

            if not os.path.exists(cfile):
                return None
            s_ms, e_ms = int(seg["start"] * 1000), int(seg["end"] * 1000)
            t_dur = max(300, e_ms - s_ms)
            clip = AudioSegment.from_file(cfile)
            if len(clip) > t_dur:
                ratio = min(1.85, len(clip) / t_dur)
                f_path = os.path.join(cache_dir, f"{ckey}_{t_dur}.mp3")
                if not (reuse_audio_cache and os.path.exists(f_path)):
                    subprocess.run(["ffmpeg", "-y", "-i", cfile, "-filter:a", f"atempo={ratio:.3f}", f_path], stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)
                if os.path.exists(f_path):
                    clip = AudioSegment.from_file(f_path)
            return (s_ms, clip)

        synced = []
        with ThreadPoolExecutor(max_workers=max(4, min(16, tts_threads))) as ex:
            for res in ex.map(make_one_audio, segments):
                if res:
                    synced.append(res)

        if has_audio_stream(video_path):
            orig_a = AudioSegment.from_file(video_path)
            master_a = AudioSegment.silent(duration=len(orig_a)) if orig_volume <= 0.01 else orig_a.apply_gain(20 * math.log10(orig_volume))
        else:
            master_a = AudioSegment.silent(duration=int((max(s["end"] for s in segments) + 2) * 1000))

        for pos_ms, clip in synced:
            master_a = master_a.overlay(clip, position=pos_ms)
        master_a.export(final_audio_path, format="adts")

    # Render video
    if render_mode == "copy":
        cmd = ["ffmpeg", "-y", "-i", video_path, "-i", final_audio_path, "-i", srt_path, "-map", "0:v:0", "-map", "1:a:0", "-map", "2:s:0", "-c:v", "copy", "-c:a", "copy", "-c:s", "mov_text", "-movflags", "+faststart", output_path]
        subprocess.run(cmd, check=True)
        progress_cb(100, "⚡ Xuất tức thì hoàn tất!")
        return {"status": "ok", "render_mode": "copy", "badge_label": "⚡ Xuất Tức Thì", "output_path": output_path}

    logo_path = os.path.join(TEMP_DIR, "watermark_logo.png")
    vf_chain, use_logo = build_filter_complex_with_logo(
        vid_w, vid_h, blur_rect, blur_sigma, blur_opacity, blur_color,
        ass_filename=ass_path, logo_path=logo_path, addon_cfg=ADDON_SETTINGS
    )

    cmd = ["ffmpeg", "-y", "-i", video_path]
    audio_input_idx = None
    next_input_idx = 1

    if enable_tts and os.path.exists(final_audio_path):
        cmd += ["-i", final_audio_path]
        audio_input_idx = next_input_idx
        next_input_idx += 1

    if use_logo:
        cmd += ["-i", logo_path]
        vf_chain = vf_chain.replace("[LOGO_IN]", f"[{next_input_idx}:v]")

    cmd += ["-filter_complex", vf_chain, "-map", "[outv]"]
    if audio_input_idx is not None:
        cmd += ["-map", f"{audio_input_idx}:a"]
    else:
        cmd += ["-map", "0:a?"]

    cmd += ["-c:v", "libx264", "-preset", "ultrafast", "-crf", "21", "-movflags", "+faststart", "-c:a", "aac", "-b:a", "192k", output_path]
    subprocess.run(cmd, check=True)
    progress_cb(100, "Xuất Video hoàn tất 100%!")
    return {"status": "ok", "render_mode": render_mode, "badge_label": "Hoàn tất 100%", "output_path": output_path}

