def probe_video_info(video_path):
    try:
        import av
        with av.open(video_path) as container:
            vstream = container.streams.video[0]
            vid_w, vid_h = vstream.width, vstream.height
            total_dur = float(container.duration / av.time_base) if container.duration else 0.0
            has_audio = len(container.streams.audio) > 0
            return vid_w, vid_h, total_dur, has_audio
    except Exception:
        cmd = ["ffprobe", "-v", "quiet", "-print_format", "json", "-show_format", "-show_streams", video_path]
        proc = subprocess.run(cmd, capture_output=True, text=True)
        info = json.loads(proc.stdout or "{}")
        vid_w, vid_h, has_audio = 1280, 720, False
        for s in info.get("streams", []):
            if s.get("codec_type") == "video":
                vid_w = int(s.get("width", 1280))
                vid_h = int(s.get("height", 720))
            elif s.get("codec_type") == "audio":
                has_audio = True
        total_dur = float(info.get("format", {}).get("duration", 0.0))
        return vid_w, vid_h, total_dur, has_audio

def format_srt_time(seconds):
    hrs = int(seconds // 3600)
    mins = int((seconds % 3600) // 60)
    secs = int(seconds % 60)
    msecs = min(999, int(round((seconds - int(seconds)) * 1000)))
    return f"{hrs:02d}:{mins:02d}:{secs:02d},{msecs:03d}"

def format_ass_time(seconds):
    hrs = int(seconds // 3600)
    mins = int((seconds % 3600) // 60)
    secs = int(seconds % 60)
    cs = min(99, int(round((seconds - int(seconds)) * 100)))
    return f"{hrs:d}:{mins:02d}:{secs:02d}.{cs:02d}"

def hex_to_ass_color(hex_color, alpha=0):
    hex_color = (hex_color or "#FFFFFF").lstrip('#')
    if len(hex_color) != 6: hex_color = "FFFFFF"
    return f"&H{alpha:02X}{hex_color[4:6].upper()}{hex_color[2:4].upper()}{hex_color[0:2].upper()}"

