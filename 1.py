# ==================== BỘ CÔNG CỤ DỊCH THUẬT ĐA ĐỘNG CƠ (GOOGLE + GEMINI HYBRID) ====================
def translate_google_batch(items, target_lang='vi', source_lang='auto'):
    """
    Dịch danh sách (id, text) qua Google Translate (Miễn phí 100%, không cần API Key).
    Xử lý theo khối 25 câu có gắn tag [[ID_x]], fallback từng câu nếu thiếu.
    """
    if not items:
        return {}
    res_map = {}
    batch_size = 25
    chunks = [items[i:i+batch_size] for i in range(0, len(items), batch_size)]
    headers = {"User-Agent": "Mozilla/5.0 (Windows NT 10.0; Win64; x64) Chrome/120.0.0.0"}

    def _call_g_chunk(chunk):
        encoded = "\n".join([f"[[ID_{sid}]] {txt}" for sid, txt in chunk if txt.strip()])
        if not encoded.strip():
            return {}
        try:
            url = "https://translate.googleapis.com/translate_a/single"
            params = {"client": "gtx", "sl": source_lang, "tl": target_lang, "dt": "t", "q": encoded}
            r = requests.get(url, params=params, headers=headers, timeout=12)
            if r.status_code == 200:
                raw_t = "".join([p[0] for p in r.json()[0] if p and p[0]])
                matches = re.finditer(r'\[\[ID_(\d+)\]\]\s*(.*?)(?=\[\[ID_\d+\]\]|$|\n)', raw_t, re.DOTALL)
                sub_res = {}
                for m in matches:
                    sid = int(m.group(1))
                    val = m.group(2).strip()
                    if val:
                        sub_res[sid] = val
                return sub_res
        except Exception:
            pass
        return {}

    with ThreadPoolExecutor(max_workers=min(len(chunks) or 1, 8)) as ex:
        futs = [ex.submit(_call_g_chunk, ch) for ch in chunks]
        for f in as_completed(futs):
            res_map.update(f.result())

    # Fallback từng câu nếu chunk nào đó bị sót dòng
    missing = [it for it in items if it[0] not in res_map and it[1].strip()]
    if missing:
        def _call_single(it):
            sid, txt = it
            try:
                url = "https://translate.googleapis.com/translate_a/single"
                params = {"client": "gtx", "sl": source_lang, "tl": target_lang, "dt": "t", "q": txt}
                r = requests.get(url, params=params, headers=headers, timeout=6)
                if r.status_code == 200:
                    val = "".join([p[0] for p in r.json()[0] if p and p[0]]).strip()
                    return sid, val
            except Exception:
                pass
            return sid, ""

        with ThreadPoolExecutor(max_workers=min(len(missing), 6)) as ex:
            for sid, val in ex.map(_call_single, missing):
                if val:
                    res_map[sid] = val

    return res_map

def translate_single_text(text, target_lang='vi', source_lang='auto'):
    if not text or not text.strip():
        return ""
    try:
        url = "https://translate.googleapis.com/translate_a/single"
        params = {"client": "gtx", "sl": source_lang, "tl": target_lang, "dt": "t", "q": text}
        headers = {"User-Agent": "Mozilla/5.0"}
        r = requests.get(url, params=params, headers=headers, timeout=8)
        if r.status_code == 200:
            return "".join([p[0] for p in r.json()[0] if p and p[0]]).strip()
    except Exception:
        pass
    return text

def parse_llm_translation_response(raw_text, expected_ids):
    res_map = {}
    if not raw_text:
        return res_map
    raw_text = re.sub(r"^```[a-zA-Z0-9_-]*\n", "", raw_text.strip(), flags=re.MULTILINE)
    raw_text = re.sub(r"\n```$", "", raw_text.strip(), flags=re.MULTILINE)

    matches = re.finditer(r'\[\[ID_(\d+)\]\]\s*(.*?)(?=\[\[ID_\d+\]\]|$|\n)', raw_text, re.DOTALL)
    for m in matches:
        sid = int(m.group(1))
        val = m.group(2).strip()
        if val and sid in expected_ids:
            res_map[sid] = val

    for line in raw_text.splitlines():
        line = line.strip()
        if not line:
            continue
        m = re.match(r'^(?:\[\s*|ID\s*|#\s*)?(\d+)(?:\])?\s*[\:\.\|\-\t\uff5c\uff1a]\s*(.+)$', line)
        if m:
            sid = int(m.group(1))
            val = m.group(2).strip()
            if sid in expected_ids and sid not in res_map and val:
                res_map[sid] = val

    return res_map

def call_gemini_single_batch(api_keys, start_key_idx, preferred_model, prompt_text):
    valid_models = []
    for m in [preferred_model, "gemini-2.0-flash", "gemini-2.0-flash-lite", "gemini-1.5-flash", "gemini-1.5-pro"]:
        if m and m not in valid_models:
            valid_models.append(m)

    base_payload = {"contents": [{"parts": [{"text": prompt_text}]}], "generationConfig": {"temperature": 0.15}}
    last_error = ""
    for k_offset in range(len(api_keys)):
        api_key = api_keys[(start_key_idx + k_offset) % len(api_keys)]
        for model_name in valid_models:
            url = f"https://generativelanguage.googleapis.com/v1beta/models/{model_name}:generateContent?key={api_key}"
            try:
                payload = json.loads(json.dumps(base_payload))
                if "thinking" in model_name:
                    payload["generationConfig"]["thinkingConfig"] = {"thinkingBudget": 0}
                resp = requests.post(url, json=payload, timeout=90)
                if resp.status_code == 400 and "thinkingConfig" in resp.text:
                    resp = requests.post(url, json=base_payload, timeout=90)
                if resp.status_code == 200:
                    return resp.json(), model_name, None
                elif resp.status_code == 429:
                    last_error = f"Model {model_name} bị giới hạn tần suất (429 Rate Limit)"
                    break
                else:
                    last_error = f"API trả về mã {resp.status_code}: {resp.text[:120]}"
            except Exception as e:
                last_error = str(e)
    return None, preferred_model, last_error

