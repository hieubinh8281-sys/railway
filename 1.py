@app.route("/api/subtitles/replace", methods=["POST"])
def api_subtitles_replace():
    """Tìm kiếm & thay thế hàng loạt từ ngữ trong phụ đề"""
    data = request.json or {}
    segments = data.get("segments", [])
    find_str = data.get("find", "").strip()
    replace_str = data.get("replace", "")
    target_col = data.get("target", "all") # 'all' | 'trans' | 'orig'
    match_case = data.get("matchCase", False)

    if not find_str:
        return jsonify({"error": "Từ khóa tìm kiếm không được để trống!"}), 400

    count = 0
    flags = 0 if match_case else re.IGNORECASE
    pattern = re.compile(re.escape(find_str), flags)

    for s in segments:
        if target_col in ("all", "orig") and "text" in s:
            new_text, n1 = pattern.subn(replace_str, s["text"])
            if n1:
                s["text"] = new_text
                count += n1
        if target_col in ("all", "trans") and "trans" in s:
            new_trans, n2 = pattern.subn(replace_str, s["trans"])
            if n2:
                s["trans"] = new_trans
                count += n2

    return jsonify({"segments": segments, "count": count, "message": f"Đã thay thế thành công {count} vị trí!"})

