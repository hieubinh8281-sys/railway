def check_admin_token(req):
    auth = req.headers.get("Authorization", "")
    token = auth.replace("Bearer ", "").strip() if "Bearer " in auth else auth.strip()
    if not token or "|" not in token:
        return False
    parts = token.split("|")
    if len(parts) != 3:
        return False
    role, exp_str, sig = parts
    if role != "admin":
        return False
    try:
        if int(exp_str) < int(time.time()):
            return False
    except ValueError:
        return False
    expected = hmac.new(SERVER_HMAC_SECRET.encode("utf-8"), f"admin|{exp_str}".encode("utf-8"), hashlib.sha256).hexdigest()[:16]
    return sig == expected

