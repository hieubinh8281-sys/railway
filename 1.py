PIPER_LOCK = Lock()

def ensure_piper_engine():
    exe_name = "piper.exe" if os.name == "nt" else "piper"
    piper_exe = os.path.join(PIPER_BIN_DIR, exe_name)
    if os.path.exists(piper_exe):
        return piper_exe

    with PIPER_LOCK:
        if os.path.exists(piper_exe):
            return piper_exe
        os.makedirs(BIN_DIR, exist_ok=True)
        print("[*] Đang tải nhân đọc giọng nói thần kinh Piper TTS (ONNX Runtime)...")
        if os.name == "nt":
            url = "https://github.com/rhasspy/piper/releases/download/2023.11.14-2/piper_windows_amd64.zip"
            archive_path = os.path.join(BIN_DIR, "piper_win.zip")
            resp = requests.get(url, stream=True, timeout=120)
            resp.raise_for_status()
            with open(archive_path, "wb") as f:
                for chunk in resp.iter_content(chunk_size=65536):
                    if chunk:
                        f.write(chunk)
            with zipfile.ZipFile(archive_path, "r") as zf:
                zf.extractall(BIN_DIR)
            os.remove(archive_path)
        else:
            url = "https://github.com/rhasspy/piper/releases/download/2023.11.14-2/piper_linux_x86_64.tar.gz"
            archive_path = os.path.join(BIN_DIR, "piper_linux.tar.gz")
            resp = requests.get(url, stream=True, timeout=120)
            resp.raise_for_status()
            with open(archive_path, "wb") as f:
                for chunk in resp.iter_content(chunk_size=65536):
                    if chunk:
                        f.write(chunk)
            with tarfile.open(archive_path, "r:gz") as tf:
                tf.extractall(BIN_DIR)
            os.remove(archive_path)
            if os.path.exists(piper_exe):
                os.chmod(piper_exe, 0o755)

    return piper_exe if os.path.exists(piper_exe) else None

def ensure_piper_voice_model(voice_id):
    model_name = voice_id.replace("piper:", "").strip()
    onnx_path = os.path.join(PIPER_MODELS_DIR, f"{model_name}.onnx")
    json_path = os.path.join(PIPER_MODELS_DIR, f"{model_name}.onnx.json")

    if os.path.exists(onnx_path) and os.path.exists(json_path) and os.path.getsize(onnx_path) > 100000:
        return onnx_path, json_path

    with PIPER_LOCK:
        if os.path.exists(onnx_path) and os.path.exists(json_path) and os.path.getsize(onnx_path) > 100000:
            return onnx_path, json_path

        parts = model_name.split("-")
        if len(parts) < 3:
            raise RuntimeError(f"Không tìm thấy file model Piper '{model_name}.onnx' trong thư mục piper_models!")

        locale = parts[0]
        lang_short = locale.split("_")[0]
        quality = parts[-1]
        speaker = "-".join(parts[1:-1])

        base_hf = f"https://huggingface.co/rhasspy/piper-voices/resolve/v1.0.0/{lang_short}/{locale}/{speaker}/{quality}/{model_name}"
        print(f"[*] Đang tải model giọng đọc Piper Studio '{model_name}' từ HuggingFace...")

        r_json = requests.get(f"{base_hf}.onnx.json", timeout=30)
        r_json.raise_for_status()
        with open(json_path, "wb") as f:
            f.write(r_json.content)

        r_onnx = requests.get(f"{base_hf}.onnx", stream=True, timeout=180)
        r_onnx.raise_for_status()
        temp_onnx = onnx_path + ".part"
        with open(temp_onnx, "wb") as f:
            for chunk in r_onnx.iter_content(chunk_size=131072):
                if chunk:
                    f.write(chunk)
        os.replace(temp_onnx, onnx_path)

    return onnx_path, json_path

def synthesize_with_piper(text, voice_id, out_file_path):
    piper_exe = ensure_piper_engine()
    if not piper_exe:
        return False
    onnx_path, _ = ensure_piper_voice_model(voice_id)

    temp_wav = out_file_path + ".piper.wav"
    try:
        proc = subprocess.run(
            [piper_exe, "--model", onnx_path, "--output_file", temp_wav],
            input=text.encode("utf-8"),
            stdout=subprocess.DEVNULL,
            stderr=subprocess.DEVNULL,
            timeout=30
        )
        if proc.returncode == 0 and os.path.exists(temp_wav) and os.path.getsize(temp_wav) > 200:
            if out_file_path.endswith(".mp3"):
                subprocess.run(
                    ["ffmpeg", "-y", "-i", temp_wav, "-c:a", "libmp3lame", "-q:a", "2", out_file_path],
                    stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL, timeout=20
                )
                os.remove(temp_wav)
            else:
                os.replace(temp_wav, out_file_path)
            return os.path.exists(out_file_path) and os.path.getsize(out_file_path) > 100
    except Exception as e:
        print(f"[!] Lỗi Piper TTS: {e}")
    finally:
        if os.path.exists(temp_wav):
            try:
                os.remove(temp_wav)
            except Exception:
                pass
    return False

def get_custom_piper_voices():
    custom_list = []
    known_ids = set()
    for lang_data in LANGUAGE_CATALOG.values():
        for v in lang_data["voices"]:
            known_ids.add(v["id"])

    if os.path.exists(PIPER_MODELS_DIR):
        for fname in os.listdir(PIPER_MODELS_DIR):
            if fname.endswith(".onnx"):
                m_name = fname[:-5]
                vid = f"piper:{m_name}"
                if vid not in known_ids and os.path.exists(os.path.join(PIPER_MODELS_DIR, f"{m_name}.onnx.json")):
                    custom_list.append({
                        "id": vid,
                        "label": f"💎 [Piper Custom] {m_name}",
                        "engine": "piper"
                    })
    return custom_list

