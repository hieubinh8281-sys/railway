def parse_srt_time(time_str):
    time_str = time_str.strip().replace('.', ',')
    parts = re.split('[:,]', time_str)
    return int(parts[0])*3600 + int(parts[1])*60 + int(parts[2]) + int(parts[3])/1000.0

def parse_srt_content(content):
    segments = []
    blocks = re.split(r'\n\s*\n', content.strip())
    idx = 1
    for block in blocks:
        lines = [l.strip() for l in block.strip().split('\n') if l.strip()]
        if len(lines) >= 2:
            time_line = lines[1] if '-->' in lines[1] else (lines[0] if '-->' in lines[0] else None)
            if not time_line:
                continue
            start_str, end_str = [t.strip() for t in time_line.split('-->')]
            text_lines = lines[2:] if time_line == lines[1] else lines[1:]
            segments.append({
                "id": idx,
                "start": round(parse_srt_time(start_str), 2),
                "end": round(parse_srt_time(end_str), 2),
                "text": " ".join(text_lines),
                "trans": ""
            })
            idx += 1
    return segments

