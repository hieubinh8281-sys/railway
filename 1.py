@app.route("/api/cloud/dispatch", methods=["POST"])
def api_cloud_dispatch():
    data = request.json or {}
    dev_id = request.headers.get("X-Nexus-Device") or data.get("device_id", "DEV-UNKNOWN")
    token = request.headers.get("X-Nexus-Session") or request.cookies.get("nexus_session_token", "")
    ua = request.user_agent.string or ""

    # Bắt buộc xác thực bản quyền thiết bị
    ok, reason, payload = validate_session_token(token, dev_id, ua)
    if not ok:
        return jsonify({"error": f"Yêu cầu kích hoạt bản quyền: {reason}", "require_license": True}), 403

    key_str = payload if isinstance(payload, str) else (payload.get("key_str", "") if isinstance(payload, dict) else str(payload or ""))
    db = load_license_db()
    k_rec = db.get("keys", {}).get(key_str, {})
    tier = k_rec.get("tier", "pro")
    quota_limit = k_rec.get("quota_limit", 50)
    quota_used = k_rec.get("quota_used", 0)

    provider = data.get("provider", "kaggle")
    # Nếu dùng Kaggle GPU mà gói là Basic thì chặn
    if provider == "kaggle" and tier == "basic":
        return jsonify({"error": "⚠️ Gói Key Basic chỉ hỗ trợ xử lý CPU. Vui lòng nâng cấp lên Key PRO để sử dụng GPU Siêu Tốc (Kaggle NVIDIA T4)!", "require_pro": True}), 403

    # Kiểm tra hạn mức Quota
    if quota_limit != -1 and quota_used >= quota_limit:
        return jsonify({"error": f"❌ Key của bạn đã hết hạn mức sử dụng ({quota_used}/{quota_limit} lượt)! Vui lòng liên hệ Admin để nạp thêm lượt.", "quota_exceeded": True}), 403

    video_path = os.path.join(TEMP_DIR, "input_video.mp4")
    if not os.path.exists(video_path):
        return jsonify({"error": "Vui lòng chọn tải Video lên trước khi chạy!"}), 400

    consume_license_quota(key_str, 1)

    data = request.json or {}
    provider = data.get("provider", "kaggle")
    task_mode = data.get("task_mode", "full")
    job_id = datetime.now().strftime("job_%H%M%S_") + uuid.uuid4().hex[:6]

    # Nếu người dùng chưa vẽ khung che mờ tay, tự động chạy SmartBlur (quét 3-5p đầu che cả hàng) trước khi gửi lên Cloud!
    st = data.get("settings", {})
    br = st.get("blurRect", {"x": 0, "y": 0, "w": 0, "h": 0})
    if int(br.get("w", 0)) < 10 and int(br.get("h", 0)) < 10 and st.get("renderMode") != "copy":
        try:
            sb_res = auto_detect_smartblur_fullrow(
                video_path,
                scan_minutes=ADDON_SETTINGS["smartblur_scan_minutes"],
                pad_y=ADDON_SETTINGS["smartblur_pad_y"],
                progress_cb=update_progress
            )
            st["blurRect"] = {"x": sb_res["x"], "y": sb_res["y"], "w": sb_res["w"], "h": sb_res["h"]}
            data["settings"] = st
        except Exception:
            pass

    # Đính kèm cấu hình Addons (Chữ mờ DVD + Logo) vào gói Job cho Cloud Worker
    logo_file = os.path.join(TEMP_DIR, "watermark_logo.png")
    data["addon_settings"] = dict(ADDON_SETTINGS)
    data["has_logo"] = os.path.exists(logo_file)

    ACTIVE_CLOUD_JOB.update({
        "job_id": job_id,
        "provider": provider,
        "status": "running",
        "task_mode": task_mode,
        "segments": data.get("segments", []),
        "locked_context": "",
        "error": None,
        "output_ready": False
    })

    job_cfg_path = os.path.join(TEMP_DIR, f"{job_id}_config.json")
    with open(job_cfg_path, "w", encoding="utf-8") as f:
        json.dump(data, f, ensure_ascii=False)

    try:
        if provider == "kaggle":
            dispatch_kaggle_t4_worker(job_id)
        elif provider == "github":
            dispatch_github_vps_worker(job_id)
        else:
            return jsonify({"error": "Provider không hợp lệ"}), 400

        return jsonify({"status": "dispatched", "job_id": job_id})
    except Exception as e:
        ACTIVE_CLOUD_JOB["status"] = "failed"
        ACTIVE_CLOUD_JOB["error"] = str(e)
        update_progress(0, "Lỗi khởi tạo Cloud Worker")
        return jsonify({"error": str(e)}), 400

